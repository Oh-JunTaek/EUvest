with open('tests/unit/test_settings.py', 'a', encoding='utf-8') as f:
    f.write('class TestLoadSettings:\n')
    f.write('    def test_load_from_yaml(self):\n')
    f.write('        with tempfile.NamedTemporaryFile(mode="w", suffix=".yaml", delete=False) as f:\n')
    f.write('            yaml.dump(\n')
    f.write('                {\n')
    f.write('                    "schema_version": "1.0",\n')
    f.write('                    "execution": {"mode": "OFFLINE_SIM", "kill_switch": True},\n')
    f.write('                    "markets": {"KRX": True, "US": False},\n')
    f.write('                },\n')
    f.write('                f,\n')
    f.write('            )\n')
    f.write('            temp_path = f.name\n\n')
    f.write('        try:\n')
    f.write('            s = load_settings(temp_path)\n')
    f.write('            assert s.execution.mode == ExecutionMode.OFFLINE_SIM\n')
    f.write('            assert s.execution.kill_switch is True\n')
    f.write('            assert s.markets.KRX is True\n')
    f.write('            assert s.markets.US is False\n')
    f.write('        finally:\n')
    f.write('            os.unlink(temp_path)\n\n')
    f.write('    def test_missing_config_raises(self):\n')
    f.write('        with pytest.raises(FileNotFoundError):\n')
    f.write('            load_settings("nonexistent.yaml")\n\n')
    f.write('class TestSettingsSingleton:\n')
    f.write('    def test_get_settings_returns_instance(self):\n')
    f.write('        reset_settings()\n')
    f.write('        s = get_settings()\n')
    f.write('        assert isinstance(s, Settings)\n')
    f.write('        assert get_settings() is s\n\n')
    f.write('    def test_reset_settings(self):\n')
    f.write('        reset_settings()\n')
    f.write('        assert get_settings() is not None\n')
    f.write('        reset_settings()\n\n')
    f.write('class TestModeChecks:\n')
    f.write('    def test_is_live_mode(self):\n')
    f.write('        s = Settings(\n')
    f.write('            execution=ExecutionConfig(mode=ExecutionMode.LIVE, allow_live_orders=True, kill_switch=False),\n')
    f.write('            broker=BrokerConfig(environment=BrokerEnvironment.LIVE),\n')
    f.write('        )\n')
    f.write('        assert s.is_live_mode() is True\n\n')
    f.write('    def test_is_paper_mode(self):\n')
    f.write('        s = Settings(\n')
    f.write('            execution=ExecutionConfig(mode=ExecutionMode.KIS_PAPER),\n')
    f.write('            broker=BrokerConfig(environment=BrokerEnvironment.PAPER),\n')
    f.write('        )\n')
    f.write('        assert s.is_paper_mode() is True\n\n')
    f.write('    def test_is_offline_mode(self):\n')
    f.write('        s = Settings()\n')
    f.write('        assert s.is_offline_mode() is True\n\n')
    f.write('class TestAllowedAssets:\n')
    f.write('    def test_get_allowed_asset_ids(self):\n')
    f.write('        s = Settings(universe={"allowed_assets": ["KRX:005930", "US:AAPL"]})\n')
    f.write('        assets = s.get_allowed_asset_ids()\n')
    f.write('        assert "KRX:005930" in assets\n')
    f.write('        assert "US:AAPL" in assets\n\n')
    f.write('    def test_empty_allowed_assets(self):\n')
    f.write('        s = Settings()\n')
    f.write('        assert s.get_allowed_asset_ids() == []\n\n')
    f.write('if __name__ == "__main__":\n')
    f.write('    pytest.main([__file__, "-v"])\n')

