with open('src/invest_agent/evaluation.py', 'a', encoding='utf-8') as f:
    f.write('    results = {}\n')
    f.write('    for horizon in horizons:\n')
    f.write('        price_date, price = _get_trading_day_offset(\n')
    f.write('            ohlcv_repo, asset_id, base_price_date or "", horizon, provider=provider\n')
    f.write('        )\n\n')
    f.write('        horizon_price = None\n')
    f.write('        horizon_return = None\n')
    f.write('        horizon_hit = None\n')
    f.write('        horizon_reason = None\n\n')
    f.write('        if price is None or price_date is None:\n')
    f.write('            horizon_reason = f"{horizon}거래일 후 가격 데이터 없음"\n')
    f.write('        else:\n')
    f.write('            # 평가 대상 종가의 확정 시각 검증 - as_of 기준으로 확인\n')
    f.write('            eval_ohlcv, _ = _get_closest_ohlcv(\n')
    f.write('                ohlcv_repo, asset_id, datetime.fromisoformat(price_date + "T00:00:00").replace(tzinfo=UTC),\n')
    f.write('                provider=provider\n')
    f.write('            )\n')
    f.write('            if not _check_price_confirmation_time(eval_ohlcv, as_of, f"{horizon}일 후 평가", []):\n')
    f.write('                horizon_reason = f"{horizon}일 후 평가: 종가 확정 시각 이후 평가 필요 (as_of={as_of.isoformat()})"\n')
    f.write('            else:\n')
    f.write('                horizon_price = price\n')
    f.write('                return_pct = ((price / base_price - Decimal("1")) * Decimal("100")).quantize(Decimal("0.0001"))\n')
    f.write('                horizon_return = return_pct\n\n')
    f.write('                if decision.outcome == DecisionOutcome.TRADE and decision.side == OrderSide.BUY:\n')
    f.write('                    horizon_hit = return_pct > Decimal("0")\n')
    f.write('                elif decision.outcome == DecisionOutcome.TRADE and decision.side == OrderSide.SELL:\n')
    f.write('                    horizon_hit = return_pct < Decimal("0")\n')
    f.write('                else:\n')
    f.write('                    horizon_hit = None\n\n')
    f.write('        results[horizon] = {\n')
    f.write('            "price": horizon_price,\n')
    f.write('            "date": price_date,\n')
    f.write('            "return_pct": horizon_return,\n')
    f.write('            "hit": horizon_hit,\n')
    f.write('            "reason": horizon_reason,\n')
    f.write('        }\n\n')
    f.write('    evaluable = all(r["price"] is not None for r in results.values())\n')
    f.write('    non_evaluable_reasons = [r["reason"] for r in results.values() if r["price"] is None]\n\n')
    f.write('    return DecisionEvaluation(\n')
    f.write('        decision_id=decision.id,\n')
    f.write('        thesis_id=decision.thesis_id,\n')
    f.write('        asset_id=asset_id,\n')
    f.write('        model_provider=decision.model_provider,\n')
    f.write('        model_name=decision.model_name,\n')
    f.write('        outcome=decision.outcome,\n')
    f.write('        side=decision.side,\n')
    f.write('        decided_at=decided_at,\n')
    f.write('        base_price=base_price,\n')
    f.write('        base_price_date=base_price_date,\n')
    f.write('        base_price_provider=base_price_provider,\n')
    f.write('        horizon_1d_price=results.get(1, {}).get("price"),\n')
    f.write('        horizon_1d_return_pct=results.get(1, {}).get("return_pct"),\n')
    f.write('        horizon_1d_hit=results.get(1, {}).get("hit"),\n')
    f.write('        horizon_1d_reason=results.get(1, {}).get("reason"),\n')
    f.write('        horizon_5d_price=results.get(5, {}).get("price"),\n')
    f.write('        horizon_5d_return_pct=results.get(5, {}).get("return_pct"),\n')
    f.write('        horizon_5d_hit=results.get(5, {}).get("hit"),\n')
    f.write('        horizon_5d_reason=results.get(5, {}).get("reason"),\n')
    f.write('        horizon_20d_price=results.get(20, {}).get("price"),\n')
    f.write('        horizon_20d_return_pct=results.get(20, {}).get("return_pct"),\n')
    f.write('        horizon_20d_hit=results.get(20, {}).get("hit"),\n')
    f.write('        horizon_20d_reason=results.get(20, {}).get("reason"),\n')
    f.write('        evaluable=evaluable,\n')
    f.write('        non_evaluable_reasons=non_evaluable_reasons,\n')
    f.write('    )\n\n')
