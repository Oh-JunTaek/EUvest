with open('src/invest_agent/evaluation.py', 'a', encoding='utf-8') as f:
    f.write('def evaluate_decision(\n')
    f.write('    decision: Decision,\n')
    f.write('    thesis_repo: ThesisRepository,\n')
    f.write('    ohlcv_repo: OHLCVRepository,\n')
    f.write('    horizons: tuple[int, ...] = EVALUATION_HORIZONS,\n')
    f.write('    max_freshness_days: int = 10,\n')
    f.write('    max_days_back: int = 10,\n')
    f.write('    as_of: datetime | None = None,\n')
    f.write('    provider: str | None = None,\n')
    f.write(') -> DecisionEvaluation:\n')
    f.write('    """단일 의사결정 평가.\n\n')
    f.write('    Args:\n')
    f.write('        decision: 평가할 의사결정\n')
    f.write('        thesis_repo: 가설 리포지토리\n')
    f.write('        ohlcv_repo: OHLCV 리포지토리\n')
    f.write('        horizons: 평가 기간 (거래일 단위)\n')
    f.write('        max_freshness_days: 데이터 최대 경과 일수\n')
    f.write('        max_days_back: 과거 데이터 검색 범위\n')
    f.write('        as_of: 평가 기준 시점 (기본값: 현재 UTC). 이 시점 이후 확정되는 가격은 사용하지 않음.\n')
    f.write('        provider: OHLCV 공급자 지정. 지정 시 해당 공급자 데이터만 사용.\n')
    f.write('    """\n')
    f.write('    thesis = thesis_repo.get(decision.thesis_id)\n')
    f.write('    if not thesis:\n')
    f.write('        return DecisionEvaluation(\n')
    f.write('            decision_id=decision.id,\n')
    f.write('            thesis_id=decision.thesis_id,\n')
    f.write('            asset_id="",\n')
    f.write('            model_provider=decision.model_provider,\n')
    f.write('            model_name=decision.model_name,\n')
    f.write('            outcome=decision.outcome,\n')
    f.write('            side=decision.side,\n')
    f.write('            decided_at=decision.decided_at,\n')
    f.write('            base_price=None,\n')
    f.write('            base_price_date=None,\n')
    f.write('            base_price_provider=None,\n')
    f.write('            horizon_1d_price=None,\n')
    f.write('            horizon_1d_return_pct=None,\n')
    f.write('            horizon_1d_hit=None,\n')
    f.write('            horizon_1d_reason="Thesis를 찾을 수 없음",\n')
    f.write('            horizon_5d_price=None,\n')
    f.write('            horizon_5d_return_pct=None,\n')
    f.write('            horizon_5d_hit=None,\n')
    f.write('            horizon_5d_reason="Thesis를 찾을 수 없음",\n')
    f.write('            horizon_20d_price=None,\n')
    f.write('            horizon_20d_return_pct=None,\n')
    f.write('            horizon_20d_hit=None,\n')
    f.write('            horizon_20d_reason="Thesis를 찾을 수 없음",\n')
    f.write('            evaluable=False,\n')
    f.write('            non_evaluable_reasons=["Thesis를 찾을 수 없음"],\n')
    f.write('        )\n\n')
    f.write('    asset_id = thesis.asset_id\n')
    f.write('    decided_at = decision.decided_at\n\n')
    f.write('    # as_of가 없으면 현재 UTC 사용\n')
    f.write('    if as_of is None:\n')
    f.write('        as_of = datetime.now(UTC)\n\n')
    f.write('    base_ohlcv, base_price_date = _get_closest_ohlcv(\n')
    f.write('        ohlcv_repo, asset_id, decided_at, provider=provider, max_days_back=10\n')
    f.write('    )\n\n')
    f.write('    base_price = None\n')
    f.write('    base_price_provider = None\n')
    f.write('    if base_ohlcv:\n')
    f.write('        base_price = base_ohlcv.close\n')
    f.write('        base_price_provider = base_ohlcv.provider if hasattr(base_ohlcv, "provider") else "OHLCV"\n\n')
    f.write('    if base_price is None or base_price <= 0:\n')
    f.write('        return DecisionEvaluation(\n')
    f.write('            decision_id=decision.id,\n')
    f.write('            thesis_id=decision.thesis_id,\n')
    f.write('            asset_id=asset_id,\n')
    f.write('            model_provider=decision.model_provider,\n')
    f.write('            model_name=decision.model_name,\n')
    f.write('            outcome=decision.outcome,\n')
    f.write('            side=decision.side,\n')
    f.write('            decided_at=decided_at,\n')
    f.write('            base_price=base_price,\n')
    f.write('            base_price_date=base_price_date,\n')
    f.write('            base_price_provider=base_price_provider,\n')
    f.write('            horizon_1d_price=None,\n')
    f.write('            horizon_1d_return_pct=None,\n')
    f.write('            horizon_1d_hit=None,\n')
    f.write('            horizon_1d_reason="기준 가격 없음 또는 0 이하",\n')
    f.write('            horizon_5d_price=None,\n')
    f.write('            horizon_5d_return_pct=None,\n')
    f.write('            horizon_5d_hit=None,\n')
    f.write('            horizon_5d_reason="기준 가격 없음 또는 0 이하",\n')
    f.write('            horizon_20d_price=None,\n')
    f.write('            horizon_20d_return_pct=None,\n')
    f.write('            horizon_20d_hit=None,\n')
    f.write('            horizon_20d_reason="기준 가격 없음 또는 0 이하",\n')
    f.write('            evaluable=False,\n')
    f.write('            non_evaluable_reasons=["기준 가격 없음 또는 0 이하"],\n')
    f.write('        )\n\n')
