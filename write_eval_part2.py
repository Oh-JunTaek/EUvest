with open('src/invest_agent/evaluation.py', 'a', encoding='utf-8') as f:
    f.write('def _is_us_dst(date: datetime) -> bool:\n')
    f.write('    if date.tzinfo is not None:\n')
    f.write('        date = date.astimezone(UTC).replace(tzinfo=None)\n')
    f.write('    year = date.year\n')
    f.write('    march_start = datetime(year, 3, 8)\n')
    f.write('    days_until_sunday = (6 - march_start.weekday()) % 7\n')
    f.write('    dst_start = march_start + timedelta(days=days_until_sunday)\n')
    f.write('    dst_start = datetime.combine(dst_start, time(7, 0))\n')
    f.write('    nov_start = datetime(year, 11, 1)\n')
    f.write('    days_until_sunday = (6 - nov_start.weekday()) % 7\n')
    f.write('    dst_end_date = nov_start + timedelta(days=days_until_sunday)\n')
    f.write('    dst_end = datetime.combine(dst_end_date, time(6, 0))\n')
    f.write('    return dst_start <= date < dst_end\n\n\n')
    f.write('def _get_market_close_utc(market: str, trade_date: str) -> datetime:\n')
    f.write('    base_date = datetime.fromisoformat(trade_date).date()\n')
    f.write('    if market == "US":\n')
    f.write('        check_dt = datetime.combine(base_date, time(0, 0), tzinfo=UTC)\n')
    f.write('        if _is_us_dst(check_dt):\n')
    f.write('            close_time = time(20, 0)\n')
    f.write('        else:\n')
    f.write('            close_time = time(21, 0)\n')
    f.write('    else:\n')
    f.write('        close_time = MARKET_CLOSE_UTC.get(market, time(0, 0))\n')
    f.write('    return datetime.combine(base_date, close_time).replace(tzinfo=UTC)\n\n\n')
    f.write('def _get_closest_ohlcv(\n')
    f.write('    repo: OHLCVRepository,\n')
    f.write('    asset_id: str,\n')
    f.write('    target_dt: datetime,\n')
    f.write('    provider: str | None = None,\n')
    f.write('    max_days_back: int = 10,\n')
    f.write(') -> tuple[OHLCV | None, str | None]:\n')
    f.write('    target_date = target_dt.date().isoformat()\n')
    f.write('    search_start = (target_dt - timedelta(days=max_days_back)).date().isoformat()\n')
    f.write('    ohlcv_list = repo.get_range(asset_id, search_start, target_date, provider=provider)\n')
    f.write('    if not ohlcv_list:\n')
    f.write('        return None, None\n')
    f.write('    for ohlcv in ohlcv_list:\n')
    f.write('        if ohlcv.timestamp.date() <= target_dt.date():\n')
    f.write('            return ohlcv, ohlcv.timestamp.date().isoformat()\n')
    f.write('    return None, None\n\n\n')
    f.write('def _get_trading_day_offset(\n')
    f.write('    repo: OHLCVRepository,\n')
    f.write('    asset_id: str,\n')
    f.write('    start_date: str,\n')
    f.write('    offset_days: int,\n')
    f.write('    provider: str | None = None,\n')
    f.write(') -> tuple[str | None, Decimal | None]:\n')
    f.write('    end_search = (datetime.fromisoformat(start_date).date() + timedelta(days=50)).isoformat()\n')
    f.write('    ohlcv_list = repo.get_range(asset_id, start_date, end_search, provider=provider)\n')
    f.write('    if not ohlcv_list:\n')
    f.write('        return None, None\n')
    f.write('    valid_days = [\n')
    f.write('        ohlcv for ohlcv in ohlcv_list\n')
    f.write('        if ohlcv.timestamp.date() > datetime.fromisoformat(start_date).date()\n')
    f.write('    ]\n')
    f.write('    valid_days.sort(key=lambda x: x.timestamp.date())\n')
    f.write('    if len(valid_days) < offset_days:\n')
    f.write('        return None, None\n')
    f.write('    target = valid_days[offset_days - 1]\n')
    f.write('    return target.timestamp.date().isoformat(), target.close\n\n\n')
    f.write('def _check_price_confirmation_time(\n')
    f.write('    ohlcv: OHLCV | None,\n')
    f.write('    as_of: datetime,\n')
    f.write('    boundary_label: str,\n')
    f.write('    reasons: list[str],\n')
    f.write(') -> bool:\n')
    f.write('    if ohlcv is None:\n')
    f.write('        return False\n')
    f.write('    market_close_utc = _get_market_close_utc(ohlcv.market, ohlcv.timestamp.date().isoformat())\n')
    f.write('    if as_of < market_close_utc:\n')
    f.write('        reasons.append(\n')
    f.write('            f"{boundary_label}: 종가 확정 시각({market_close_utc.isoformat()}) 이후 평가 필요 "\n')
    f.write('            f"(평가 기준: {as_of.isoformat()})"\n')
    f.write('        )\n')
    f.write('        return False\n')
    f.write('    return True\n\n\n')
