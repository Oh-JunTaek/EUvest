with open('src/invest_agent/evaluation.py', 'a', encoding='utf-8') as f:
    f.write('def evaluate_decisions(\n')
    f.write('    db_path: str,\n')
    f.write('    limit: int = 50,\n')
    f.write('    asset: str | None = None,\n')
    f.write('    model: str | None = None,\n')
    f.write('    horizon: int | None = None,\n')
    f.write('    as_of: datetime | None = None,\n')
    f.write('    provider: str | None = None,\n')
    f.write(') -> tuple[list[DecisionEvaluation], list[ModelEvaluationSummary]]:\n')
    f.write('    """최근 N개 의사결정 평가.\n\n')
    f.write('    Args:\n')
    f.write('        db_path: SQLite DB 경로\n')
    f.write('        limit: 조회할 의사결정 개수\n')
    f.write('        asset: 특정 종목만 평가 (예: KRX:005930)\n')
    f.write('        model: 특정 모델만 평가\n')
    f.write('        horizon: 표시할 평가 기간 (1, 5, 20 중 하나)\n')
    f.write('        as_of: 평가 기준 시점 (기본값: 현재 UTC)\n')
    f.write('        provider: OHLCV 공급자 지정\n')
    f.write('    """\n')
    f.write('    if not Path(db_path).exists():\n')
    f.write('        raise FileNotFoundError(f"DB 파일이 없습니다: {db_path}")\n\n')
    f.write('    thesis_repo = ThesisRepository(db_path)\n')
    f.write('    ohlcv_repo = OHLCVRepository(db_path)\n')
    f.write('    decision_repo = DecisionRepository(db_path)\n\n')
    f.write('    decisions = decision_repo.get_latest(limit)\n\n')
    f.write('    if asset:\n')
    f.write('        thesis_repo = ThesisRepository(db_path)\n')
    f.write('        filtered = []\n')
    f.write('        for d in decisions:\n')
    f.write('            thesis = thesis_repo.get(d.thesis_id)\n')
    f.write('            if thesis and thesis.asset_id == asset:\n')
    f.write('                filtered.append(d)\n')
    f.write('        decisions = filtered\n\n')
    f.write('    if model:\n')
    f.write('        decisions = [d for d in decisions if d.model_name == model or d.model_provider == model]\n\n')
    f.write('    evaluations = []\n')
    f.write('    for decision in decisions:\n')
    f.write('        eval_result = evaluate_decision(\n')
    f.write('            decision,\n')
    f.write('            thesis_repo,\n')
    f.write('            ohlcv_repo,\n')
    f.write('            as_of=as_of,\n')
    f.write('            provider=provider,\n')
    f.write('        )\n')
    f.write('        evaluations.append(eval_result)\n\n')
    f.write('    model_summaries = _compute_model_summaries(evaluations)\n\n')
    f.write('    return evaluations, model_summaries\n')
