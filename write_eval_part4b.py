with open('src/invest_agent/evaluation.py', 'a', encoding='utf-8') as f:
    f.write('def _compute_model_summaries(evaluations: list[DecisionEvaluation]) -> list[ModelEvaluationSummary]:\n')
    f.write('    """모델별 평가 요약 계산."""\n')
    f.write('    model_groups: dict[tuple[str, str], list[DecisionEvaluation]] = defaultdict(list)\n')
    f.write('    for eval_result in evaluations:\n')
    f.write('        key = (eval_result.model_provider, eval_result.model_name)\n')
    f.write('        model_groups[key].append(eval_result)\n\n')
    f.write('    summaries = []\n\n')
    f.write('    for (provider, name), evals in model_groups.items():\n')
    f.write('        total = len(evals)\n')
    f.write('        buy_count = sum(1 for e in evals if e.outcome == DecisionOutcome.TRADE and e.side == OrderSide.BUY)\n')
    f.write('        sell_count = sum(1 for e in evals if e.outcome == DecisionOutcome.TRADE and e.side == OrderSide.SELL)\n')
    f.write('        no_trade_count = sum(1 for e in evals if e.outcome == DecisionOutcome.NO_TRADE)\n')
    f.write('        blocked_count = sum(1 for e in evals if e.outcome == DecisionOutcome.BLOCKED)\n')
    f.write('        error_count = sum(1 for e in evals if e.outcome == DecisionOutcome.ERROR)\n\n')
    f.write('        evaluated = sum(1 for e in evals if e.evaluable)\n')
    f.write('        unevaluable = sum(1 for e in evals if not e.evaluable)\n\n')
    f.write('        buy_1d = [e for e in evals if e.outcome == DecisionOutcome.TRADE and e.side == OrderSide.BUY and e.horizon_1d_hit is not None]\n')
    f.write('        sell_1d = [e for e in evals if e.outcome == DecisionOutcome.TRADE and e.side == OrderSide.SELL and e.horizon_1d_hit is not None]\n')
    f.write('        buy_hit_1d = sum(1 for e in buy_1d if e.horizon_1d_hit)\n')
    f.write('        sell_hit_1d = sum(1 for e in sell_1d if e.horizon_1d_hit)\n')
    f.write('        total_1d = len(buy_1d) + len(sell_1d)\n')
    f.write('        total_hit_1d = buy_hit_1d + sell_hit_1d\n\n')
    f.write('        buy_hit_rate_1d = (Decimal(buy_hit_1d) / Decimal(len(buy_1d)) * Decimal("100")).quantize(Decimal("0.01")) if buy_1d else None\n')
    f.write('        sell_hit_rate_1d = (Decimal(sell_hit_1d) / Decimal(len(sell_1d)) * Decimal("100")).quantize(Decimal("0.01")) if sell_1d else None\n')
    f.write('        total_hit_rate_1d = (Decimal(total_hit_1d) / Decimal(total_1d) * Decimal("100")).quantize(Decimal("0.01")) if total_1d else None\n\n')
    f.write('        buy_5d = [e for e in evals if e.outcome == DecisionOutcome.TRADE and e.side == OrderSide.BUY and e.horizon_5d_hit is not None]\n')
    f.write('        sell_5d = [e for e in evals if e.outcome == DecisionOutcome.TRADE and e.side == OrderSide.SELL and e.horizon_5d_hit is not None]\n')
    f.write('        buy_hit_5d = sum(1 for e in buy_5d if e.horizon_5d_hit)\n')
    f.write('        sell_hit_5d = sum(1 for e in sell_5d if e.horizon_5d_hit)\n')
    f.write('        total_5d = len(buy_5d) + len(sell_5d)\n')
    f.write('        total_hit_5d = buy_hit_5d + sell_hit_5d\n\n')
    print('Part 4b written')